static int pbkdf2_sha256_selftest(pbkdf2_iter_fn iterate)
{
    uint8_t pw[80];
    uint32_t ist[16][8], ost[16][8], u[16][8];
    for (int k = 0; k < 3; k++)
    {
        int len = PBKDF2_TEST_LENGTHS[k];
        for (int l = 0; l < 16; l++)
        {
            for (int q = 0; q < len; q++) pw[q] = (uint8_t)(0x21 + (l * 17 + q * 7) % 94);
            hmac_sha256_states(pw, (size_t)len, ist[l], ost[l]);
            pbkdf2_sha256_u1(ist[l], ost[l], PBKDF2_TEST_SALT, sizeof PBKDF2_TEST_SALT, 1, u[l]);
        }
        iterate(ist, ost, u, 7);
        if (memcmp(u, PBKDF2_TEST_ANSWERS[k], sizeof u) != 0) return 0;
    }
    return 1;
}
